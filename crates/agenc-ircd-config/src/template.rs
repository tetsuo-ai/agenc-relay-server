fn render_limits_privacy(out: &mut String) {
    let _ = writeln!(out, "[limits]");
    let _ = writeln!(
        out,
        "# Every key is optional with its Appendix C.6 default and is reloadable downward."
    );
    for row in &crate::limits::LIMIT_ROWS {
        let _ = writeln!(
            out,
            "# {} = {} ({}..{})",
            row.name, row.bound.default, row.bound.minimum, row.bound.maximum
        );
    }
    let _ = writeln!(out, "\n[privacy]");
    let _ = writeln!(out, "# 1..720 hours; reloadable downward.");
    let _ = writeln!(out, "log_retention_hours = 24");
    let _ = writeln!(out, "history_enabled = false");
    let _ = writeln!(out, "# 1h, 24h, or 7d.");
    let _ = writeln!(out, "history_default = \"24h\"");
    let _ = writeln!(out, "# 1..50 milliseconds.");
    let _ = writeln!(out, "secret_lookup_floor_milliseconds = 5");
    let _ = writeln!(out, "# 1..10000.");
    let _ = writeln!(out, "whowas_records = 10000\n");
}

