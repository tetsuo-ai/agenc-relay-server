#!/usr/bin/env python3
"""Generate deterministic Stage-03 task and adversarial-sequence evidence."""

from __future__ import annotations

import sys
from pathlib import Path

SUMMARY_OUTPUT = "conformance/generated-stage-three.toml"
SEQUENCE_OUTPUT = "test-data/property/domain-stage-three-v1.steps"
TASK_EVIDENCE = (
    ("S03-001", "EVID-S03-001-IDENTITIES"),
    ("S03-002", "EVID-S03-002-CHANNELS"),
    ("S03-003", "EVID-S03-003-PROJECTIONS"),
    ("S03-004", "EVID-S03-004-COMMANDS"),
    ("S03-005", "EVID-S03-005-AUTHORIZATION"),
    ("S03-006", "EVID-S03-006-DELIVERY-PLANS"),
    ("S03-007", "EVID-S03-007-MODERATION"),
    ("S03-008", "EVID-S03-008-HISTORY-E2EE"),
    ("S03-009", "EVID-S03-009-MUTATION-PLANS"),
    ("S03-010", "EVID-S03-010-EXPLICIT-INPUTS"),
    ("S03-011", "EVID-S03-011-REFERENCE-MODEL"),
    ("S03-012", "EVID-S03-012-SEQUENCES"),
    ("S03-900", "EVID-S03-900-STAGE-GATE"),
)
VISIBILITIES = ("listed", "unlisted", "secret")
SCENARIO_FAMILIES = (
    "membership-role-mode",
    "nickname-reuse-recreation",
    "invite-account-switch",
    "account-deletion-federation",
)
SCENARIOS = tuple(
    (case, VISIBILITIES[case % len(VISIBILITIES)], SCENARIO_FAMILIES[case // 3])
    for case in range(12)
)
REJECTIONS = (
    ("duplicate-nickname", "Duplicate"),
    ("stale-channel-instance", "Stale"),
    ("role-escalation", "Forbidden"),
    ("stale-session-generation", "Stale"),
    ("federation-duplicate", "Stale"),
    ("federation-gap", "Gap"),
    ("stale-account-deletion", "Stale"),
)


def render_sequences() -> str:
    """Render the finite cross-product consumed by the Rust model test."""
    lines = [
        "# Generated by scripts/generate-stage-three.py; do not edit by hand.",
        "# kind|case-or-name|visibility-or-error|scenario",
    ]
    for case, visibility, family in SCENARIOS:
        lines.append(f"CASE|{case}|{visibility}|{visibility}-{family}")
    for name, error in REJECTIONS:
        lines.append(f"REJECT|{name}|{error}|state-unchanged")
    return "\n".join(lines) + "\n"


def render_summary() -> str:
    """Render task bindings and generated-sequence dimensions."""
    lines = [
        "# Generated by scripts/generate-stage-three.py; do not edit by hand.",
        "schema_version = 1",
        f'sequence_source = "{SEQUENCE_OUTPUT}"',
        "generated_cases = 12",
        f"rejection_cases = {len(REJECTIONS)}",
        "",
    ]
    for task, evidence in TASK_EVIDENCE:
        lines.extend(
            [
                "[[task]]",
                f'id = "{task}"',
                f'evidence_id = "{evidence}"',
                "",
            ]
        )
    for visibility in VISIBILITIES:
        lines.extend(["[[visibility]]", f'name = "{visibility}"', ""])
    for case, visibility, family in SCENARIOS:
        lines.extend(
            [
                "[[scenario]]",
                f"case = {case}",
                f'name = "{visibility}-{family}"',
                f'visibility = "{visibility}"',
                "",
            ]
        )
    for name, error in REJECTIONS:
        lines.extend(
            [
                "[[rejection]]",
                f'name = "{name}"',
                f'error = "{error}"',
                "unchanged = true",
                "",
            ]
        )
    return "\n".join(lines)


def main() -> None:
    """Write both outputs or compare them without mutation."""
    root = Path(__file__).resolve().parent.parent
    outputs = {
        root / SUMMARY_OUTPUT: render_summary(),
        root / SEQUENCE_OUTPUT: render_sequences(),
    }
    if sys.argv[1:] == ["--check"]:
        for path, expected in outputs.items():
            if path.read_text(encoding="utf-8") != expected:
                raise SystemExit(f"Stage-03 generated output is stale: {path}")
        print("Stage-03 generated surfaces: ok")
        return
    if sys.argv[1:]:
        raise SystemExit("usage: generate-stage-three.py [--check]")
    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(root)}")


if __name__ == "__main__":
    main()
