#!/usr/bin/env python3
"""Generate deterministic Stage-03 task and adversarial-sequence evidence."""

from __future__ import annotations

import sys
from pathlib import Path

SUMMARY_OUTPUT = "conformance/generated-stage-three.toml"
SEQUENCE_OUTPUT = "test-data/property/domain-stage-three-v1.steps"
TASK_EVIDENCE = (
    ("S03-001", "EVID-S03-001-IDENTITIES"),
    ("S03-002", "EVID-S03-002-CHANNELS"),
    ("S03-003", "EVID-S03-003-PROJECTIONS"),
    ("S03-004", "EVID-S03-004-COMMANDS"),
    ("S03-005", "EVID-S03-005-AUTHORIZATION"),
    ("S03-006", "EVID-S03-006-DELIVERY-PLANS"),
    ("S03-007", "EVID-S03-007-MODERATION"),
    ("S03-008", "EVID-S03-008-HISTORY-E2EE"),
    ("S03-009", "EVID-S03-009-MUTATION-PLANS"),
    ("S03-010", "EVID-S03-010-EXPLICIT-INPUTS"),
    ("S03-011", "EVID-S03-011-REFERENCE-MODEL"),
    ("S03-012", "EVID-S03-012-SEQUENCES"),
    ("S03-900", "EVID-S03-900-STAGE-GATE"),
)
SCHEMA_VERSION = 2
GENERATOR_VERSION = 2
SEED_COUNT = 256
MAX_STEPS = 64
SEED_BASE = 0xA63C_0300_0000_0001
SEED_STRIDE = 0x9E37_79B9_7F4A_7C15
REGRESSIONS = (
    ("invite-metadata-parity", 0, 16, 0x28E9_87FA_8CC9_23A5),
    ("account-delete-multi-session", 0, 26, 0x1F32_FDCF_E748_A2EC),
)


def seed_at(index: int) -> int:
    """Return one wrapped 64-bit seed from the reviewed arithmetic range."""
    return (SEED_BASE + SEED_STRIDE * index) & ((1 << 64) - 1)


def render_sequences() -> str:
    """Render the bounded seed range and retained replay prefixes."""
    lines = [
        "# Generated by scripts/generate-stage-three.py; do not edit by hand.",
        "# The Rust test expands this range and compares both models after every step.",
        "# REGRESSION|name|seed|minimal-prefix-steps|operation-fingerprint",
        f"CONFIG|schema-version|{SCHEMA_VERSION}",
        f"CONFIG|generator-version|{GENERATOR_VERSION}",
        f"CONFIG|seed-count|{SEED_COUNT}",
        f"CONFIG|max-steps|{MAX_STEPS}",
        "CONFIG|snapshot-cadence|after-every-step",
        f"SEED-RANGE|0x{SEED_BASE:016x}|0x{SEED_STRIDE:016x}|{SEED_COUNT}",
    ]
    for name, seed_index, steps, fingerprint in REGRESSIONS:
        lines.append(
            f"REGRESSION|{name}|0x{seed_at(seed_index):016x}|{steps}|"
            f"0x{fingerprint:016x}"
        )
    return "\n".join(lines) + "\n"


def render_summary() -> str:
    """Render task bindings and executable model-test bounds."""
    lines = [
        "# Generated by scripts/generate-stage-three.py; do not edit by hand.",
        f"schema_version = {SCHEMA_VERSION}",
        f'sequence_source = "{SEQUENCE_OUTPUT}"',
        f"generator_version = {GENERATOR_VERSION}",
        f"seed_count = {SEED_COUNT}",
        f"max_steps = {MAX_STEPS}",
        f"minimum_step_checks = {SEED_COUNT * MAX_STEPS}",
        'snapshot_cadence = "after-every-step"',
        'rejection_atomicity = "both-models"',
        'failure_shrink = "minimal-failing-prefix"',
        f"regression_count = {len(REGRESSIONS)}",
        f"seed_base = 0x{SEED_BASE:016x}",
        f"seed_stride = 0x{SEED_STRIDE:016x}",
        "",
    ]
    for task, evidence in TASK_EVIDENCE:
        lines.extend(
            [
                "[[task]]",
                f'id = "{task}"',
                f'evidence_id = "{evidence}"',
                "",
            ]
        )
    for name, seed_index, steps, fingerprint in REGRESSIONS:
        lines.extend(
            [
                "[[regression]]",
                f'name = "{name}"',
                f"seed = 0x{seed_at(seed_index):016x}",
                f"steps = {steps}",
                f"fingerprint = 0x{fingerprint:016x}",
                "",
            ]
        )
    return "\n".join(lines)


def main() -> None:
    """Write both outputs or compare them without mutation."""
    root = Path(__file__).resolve().parent.parent
    outputs = {
        root / SUMMARY_OUTPUT: render_summary(),
        root / SEQUENCE_OUTPUT: render_sequences(),
    }
    if sys.argv[1:] == ["--check"]:
        for path, expected in outputs.items():
            if path.read_text(encoding="utf-8") != expected:
                raise SystemExit(f"Stage-03 generated output is stale: {path}")
        print("Stage-03 generated surfaces: ok")
        return
    if sys.argv[1:]:
        raise SystemExit("usage: generate-stage-three.py [--check]")
    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(root)}")


if __name__ == "__main__":
    main()
