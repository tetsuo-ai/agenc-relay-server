#!/usr/bin/env python3
"""Generate the reviewable Stage-02 wire-surface summary."""

from __future__ import annotations

import sys
import tomllib
from pathlib import Path

OUTPUT = "conformance/generated-stage-two.toml"
TASK_EVIDENCE = (
    ("S02-001", "EVID-S02-001-FRAMING"),
    ("S02-002", "EVID-S02-002-WEBSOCKET"),
    ("S02-003", "EVID-S02-003-TAGS"),
    ("S02-004", "EVID-S02-004-PARSER"),
    ("S02-005", "EVID-S02-005-CAP"),
    ("S02-006", "EVID-S02-006-REGISTRATION"),
    ("S02-007", "EVID-S02-007-AUTH"),
    ("S02-008", "EVID-S02-008-RENDER"),
    ("S02-009", "EVID-S02-009-REPLIES"),
    ("S02-010", "EVID-S02-010-TRANSCRIPT"),
    ("S02-011", "EVID-S02-011-FUZZ"),
    ("S02-900", "EVID-S02-900-STAGE-GATE"),
)


def render(root: Path) -> str:
    """Render tasks and flattened mechanical budgets in stable order."""
    budgets = tomllib.loads(
        (root / "test-data/vectors/client-wire-budgets.toml").read_text(
            encoding="utf-8"
        )
    )
    lines = [
        "# Generated by scripts/generate-stage-two.py; do not edit by hand.",
        "schema_version = 1",
        'source = "test-data/vectors/client-wire-budgets.toml"',
        "",
    ]
    for task, evidence in TASK_EVIDENCE:
        lines.extend(
            [
                "[[task]]",
                f'id = "{task}"',
                f'evidence_id = "{evidence}"',
                "",
            ]
        )
    for section in sorted(key for key in budgets if key not in {"schema_version", "evidence_id"}):
        values = budgets[section]
        if not isinstance(values, dict):
            raise ValueError(f"budget section is not a table: {section}")
        for name in sorted(values):
            value = values[name]
            if not isinstance(value, int) or value < 0:
                raise ValueError(f"budget value is not unsigned: {section}.{name}")
            lines.extend(
                [
                    "[[budget]]",
                    f'name = "{section}.{name}"',
                    f"value = {value}",
                    "",
                ]
            )
    return "\n".join(lines)


def main() -> None:
    """Write generated output or compare it without mutation."""
    root = Path(__file__).resolve().parent.parent
    expected = render(root)
    output = root / OUTPUT
    if sys.argv[1:] == ["--check"]:
        actual = output.read_text(encoding="utf-8")
        if actual != expected:
            raise SystemExit("Stage-02 generated surface is stale")
        print("Stage-02 generated surface: ok")
        return
    if sys.argv[1:]:
        raise SystemExit("usage: generate-stage-two.py [--check]")
    output.write_text(expected, encoding="utf-8")
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
